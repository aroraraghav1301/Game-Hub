-- Raghav's Game Hub upgrade (run in Supabase SQL Editor)
-- Adds owner-managed tags and anonymous event analytics.

ALTER TABLE public.games ADD COLUMN IF NOT EXISTS tags text[] NOT NULL DEFAULT '{}';

CREATE TABLE IF NOT EXISTS public.game_hub_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type text NOT NULL CHECK (event_type IN ('visit','play')),
    game_id text,
    game_name text,
    visitor_key text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.game_hub_events ENABLE ROW LEVEL SECURITY;

-- Public visitors can add event rows, but cannot read or edit analytics.
DROP POLICY IF EXISTS "Anyone can record Game Hub events" ON public.game_hub_events;
CREATE POLICY "Anyone can record Game Hub events"
ON public.game_hub_events FOR INSERT TO anon, authenticated
WITH CHECK (
    event_type IN ('visit','play')
    AND length(visitor_key) BETWEEN 8 AND 100
    AND (game_id IS NULL OR length(game_id) <= 100)
    AND (game_name IS NULL OR length(game_name) <= 200)
);

-- Only the configured owner account can read analytics.
DROP POLICY IF EXISTS "Owner can read Game Hub analytics" ON public.game_hub_events;
CREATE POLICY "Owner can read Game Hub analytics"
ON public.game_hub_events FOR SELECT TO authenticated
USING (auth.uid() = '548419b4-f0c2-427d-9e4c-9b729e566f3b'::uuid);

GRANT INSERT ON public.game_hub_events TO anon, authenticated;
GRANT SELECT ON public.game_hub_events TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.game_hub_events_id_seq TO anon, authenticated;
GRANT SELECT ON public.games TO anon, authenticated;
